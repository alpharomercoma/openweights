#!/usr/bin/env python3
"""Render the backend-parity comparison from the JSON reports the phone produced.

Pairs each ExecuTorch report with the llama.cpp report of the same family, grades side
by side, and writes the markdown document. The grades came from `ParitySuite` on the
device; this only arranges them, so rerunning after a backend change diffs mechanically.
"""

from __future__ import annotations

import argparse
import json
import re
from datetime import date
from pathlib import Path

# Family is read off the file name the same way PromptTemplates.forModel does it:
# lowercase, separators dropped, first match wins, lookalikes first.
FAMILIES = [
    ("qwen35", None),
    ("qwen3", "Qwen3"),
    ("qwen25", "Qwen2.5"),
    ("smollm2", "SmolLM2"),
    ("smollm3", "SmolLM3"),
    ("llama32", "Llama 3.2"),
    ("phi4mini", "Phi-4-mini"),
    ("gemma3", "Gemma 3"),
    ("lfm25", "LFM 2.5"),
    ("lfm2", "LFM 2.5"),
]

CASES = [
    "trap-arithmetic",
    "multi-step-change",
    "format-constraint",
    "extraction",
    "memory-across-turns",
    "tool-call",
    "tool-result",
]

MARKS = {"pass": "✅", "fail": "❌", "skipped": "—", "error": "💥", None: "·"}


def family_of(name: str) -> str | None:
    normal = re.sub(r"[^a-z0-9]", "", name.lower())
    for key, family in FAMILIES:
        if key in normal:
            return family
    return None


def load_reports(results_dir: Path):
    reports = {}
    for path in sorted(results_dir.glob("*.json")):
        report = json.loads(path.read_text())
        engine = "executorch" if "ExecuTorch" in report.get("engine", "") else "llamacpp"
        family = family_of(report["model"])
        if family:
            reports.setdefault(family, {})[engine] = report
    return reports


def case_map(report) -> dict:
    return {case["id"]: case for case in report.get("cases", [])}


def speed(case) -> str:
    prefill = case.get("prompt_tokens", 0)
    prefill_ms = case.get("prefill_ms", 0)
    decode = case.get("generated_tokens", 0)
    decode_ms = case.get("decode_ms", 0)
    parts = []
    if prefill and prefill_ms:
        parts.append(f"{prefill / prefill_ms * 1000:.0f} tok/s in")
    if decode > 1 and decode_ms:
        parts.append(f"{(decode - 1) / decode_ms * 1000:.1f} tok/s out")
    return ", ".join(parts) or "n/a"


def render(reports) -> str:
    lines = [
        "# Backend parity: ExecuTorch vs llama.cpp, same prompts, same phone",
        "",
        f"Generated by `tools/eval/run_matrix.sh` on {date.today().isoformat()}. "
        "Greedy decoding on both engines (temperature 0, topK 1), so a rerun after a "
        "backend change reproduces; grades are the device's own, from `ParitySuite`. "
        "Quantisations differ where the publishers' do (a `.pte` is typically 8da4w, "
        "the GGUF counterpart Q4_K_M), so this compares capability, not bit-parity.",
        "",
    ]

    for family in sorted(reports):
        pair = reports[family]
        et, gg = pair.get("executorch"), pair.get("llamacpp")
        lines.append(f"## {family}")
        lines.append("")
        if et:
            lines.append(f"- ExecuTorch model: `{et['model']}`")
        if gg:
            lines.append(f"- llama.cpp model: `{gg['model']}`")
        lines.append("")
        lines.append("| Case | ExecuTorch | llama.cpp | ExecuTorch speed | llama.cpp speed |")
        lines.append("|---|---|---|---|---|")
        et_cases = case_map(et) if et else {}
        gg_cases = case_map(gg) if gg else {}
        for case_id in CASES:
            a, b = et_cases.get(case_id), gg_cases.get(case_id)
            lines.append(
                f"| {case_id} "
                f"| {MARKS[a.get('status') if a else None]} "
                f"| {MARKS[b.get('status') if b else None]} "
                f"| {speed(a) if a else '·'} "
                f"| {speed(b) if b else '·'} |",
            )
        lines.append("")

        # Divergent answers are the part worth reading, so quote them.
        for case_id in CASES:
            a, b = et_cases.get(case_id), gg_cases.get(case_id)
            if not a or not b:
                continue
            if a.get("status") != b.get("status"):
                lines.append(f"**{case_id}** diverged:")
                lines.append("")
                lines.append(f"- ExecuTorch ({a.get('status')}): {snippet(a)}")
                lines.append(f"- llama.cpp ({b.get('status')}): {snippet(b)}")
                lines.append("")
    return "\n".join(lines) + "\n"


def snippet(case) -> str:
    calls = case.get("calls") or []
    if calls:
        call = calls[0]
        return f"call `{call['name']}({call['arguments']})`"
    content = (case.get("content") or case.get("error") or "").strip().replace("\n", " ")
    return f"“{content[:220]}”" if content else "(empty)"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("results_dir", type=Path)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()

    reports = load_reports(args.results_dir)
    if not reports:
        raise SystemExit(f"no reports in {args.results_dir}")
    args.out.write_text(render(reports))
    print(f"wrote {args.out} ({len(reports)} families)")


if __name__ == "__main__":
    main()
