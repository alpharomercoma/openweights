"""Render the graded public-benchmark reports as one matrix.

    python3 tools/eval/bench/report.py tools/eval/results --out docs/research/benchmark-matrix.md

One table per benchmark set: rows are families, columns are engine x phone, cells are
passed/answered. A second table carries the median wall time per prompt. Reports for the
same model and phone from several set runs are merged, later files winning per prompt.
"""
import argparse, json, statistics
from collections import defaultdict
from pathlib import Path

DEVICES = [("qdc-", "8 Gen 3"), ("tensor-", "Tensor G5"), ("exynos2500-", "Exynos 2500"),
           ("exynos-", "Exynos 2400"), ("elite-", "8 Elite"), ("", "D9400")]
ORDER = ["D9400", "8 Gen 3", "8 Elite", "Tensor G5", "Exynos 2400", "Exynos 2500"]
FAMILIES = [("gemma", "Gemma 3"), ("lfm", "LFM 2.5"), ("llama", "Llama 3.2"),
            ("qwen3", "Qwen3"), ("smollm3", "SmolLM3")]
SETS = [("gsm8k", "GSM8K"), ("ifeval", "IFEval"), ("bfcl", "BFCL")]


def device_of(name: str) -> str:
    for prefix, label in DEVICES:
        if prefix and name.startswith(prefix):
            return label
    # Unprefixed reports are the phone in hand; anything else prefixed is a mistake to
    # raise, not a column to invent.
    head = name.split("-")[0].lower()
    if head in {"tensor", "exynos", "elite", "qdc", "poco", "pixel", "galaxy", "dimensity", "snapdragon"} \
            or head.startswith(("exynos", "tensor", "qdc")):
        raise ValueError(f"unknown device prefix in {name}")
    return "D9400"


def family_of(model: str):
    m = model.lower()
    for key, label in FAMILIES:
        if key in m:
            return label
    return None


def load(root: Path):
    cells = defaultdict(dict)  # (family, engine, device) -> {prompt id: case}
    for path in sorted(root.glob("*.bench*.graded.json")):
        r = json.loads(path.read_text())
        engine = "ExecuTorch" if "ExecuTorch" in r["engine"] else "llama.cpp"
        fam = family_of(r["model"])
        if fam:
            for c in r["cases"]:
                slot = cells[(fam, engine, device_of(path.name))]
                have = slot.get(c["id"])
                # A rerun's file sorts after the original; a graded answer never loses to
                # an error or a skip, whichever file came later.
                if have and have.get("grade") in ("pass", "fail") and c.get("grade") not in ("pass", "fail"):
                    continue
                slot[c["id"]] = c
    return cells


def render(cells) -> str:
    devices = [d for d in ORDER if any(k[2] == d for k in cells)]
    cols = [(e, d) for e in ("ExecuTorch", "llama.cpp") for d in devices]
    out = ["# Public benchmarks: ExecuTorch vs llama.cpp on five SoCs", "",
           "Generated by `tools/eval/bench/report.py` from the graded reports in "
           "`tools/eval/results/`. Greedy, thinking off on both engines, one seeded subset "
           "(`tools/eval/bench/benchmarks.json`: 30 GSM8K test questions, 30 IFEval prompts, "
           "30 BFCL v3 simple and multiple calls) answered by every family on every phone. "
           "A cell is passed/answered; a dash is a family with no tool syntax or no report "
           "yet. Replies are capped at 640 tokens (384 for BFCL), so an IFEval instruction "
           "that needs more than that fails on every engine alike. Grading rules are in "
           "`grade.py`.", ""]
    for key, label in SETS:
        out += [f"## {label}", "", "| Family | " + " | ".join(f"{e} {d}" for e, d in cols) + " |",
                "|---|" + "---|" * len(cols)]
        for _, fam in FAMILIES:
            row = [fam]
            for e, d in cols:
                cs = [c for c in cells.get((fam, e, d), {}).values() if c["set"] == key]
                graded = [c for c in cs if c.get("grade") in ("pass", "fail")]
                if not graded:
                    row.append("—")
                else:
                    p = sum(c["grade"] == "pass" for c in graded)
                    row.append(f"{p}/{len(graded)}")
            out.append("| " + " | ".join(row) + " |")
        out.append("")
    for label, num, den in [("Median prefill tokens per second", "prompt_tokens", "prefill_ms"),
                            ("Median decode tokens per second", "generated_tokens", "decode_ms")]:
        out += [f"## {label}", "",
                "| Family | " + " | ".join(f"{e} {d}" for e, d in cols) + " |",
                "|---|" + "---|" * len(cols)]
        for _, fam in FAMILIES:
            row = [fam]
            for e, d in cols:
                # The first generated token's latency is prefill's; decode rate counts the
                # rest, the way GenerationStats and compare.py do.
                first = 1 if num == "generated_tokens" else 0
                rates = [(c[num] - first) / c[den] * 1000 for c in cells.get((fam, e, d), {}).values()
                         if c.get(den) and c.get(num, 0) > 1]
                row.append(f"{statistics.median(rates):.0f}" if rates else "—")
            out.append("| " + " | ".join(row) + " |")
        out.append("")
    out += ["## Median seconds per prompt", "",
            "| Family, set | " + " | ".join(f"{e} {d}" for e, d in cols) + " |",
            "|---|" + "---|" * len(cols)]
    for _, fam in FAMILIES:
        for key, label in SETS:
            row = [f"{fam}, {label}"]
            any_val = False
            for e, d in cols:
                walls = [c["wall_ms"] / 1000 for c in cells.get((fam, e, d), {}).values()
                         if c["set"] == key and c.get("wall_ms")]
                if walls:
                    row.append(f"{statistics.median(walls):.1f}")
                    any_val = True
                else:
                    row.append("—")
            if any_val:
                out.append("| " + " | ".join(row) + " |")
    out.append("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("results")
    ap.add_argument("--out")
    a = ap.parse_args()
    text = render(load(Path(a.results)))
    if a.out:
        Path(a.out).write_text(text)
        print(f"wrote {a.out}")
    else:
        print(text)


if __name__ == "__main__":
    main()
