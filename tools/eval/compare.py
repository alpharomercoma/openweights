#!/usr/bin/env python3
"""Render the backend-parity comparison from the JSON reports the phone produced.

Pairs each ExecuTorch report with the llama.cpp report of the same family, grades side
by side, and writes the markdown document. The grades came from `ParitySuite` on the
device; this only arranges them, so rerunning after a backend change diffs mechanically.
"""

from __future__ import annotations

import argparse
import json
import re
from datetime import date
from pathlib import Path

# Family is read off the file name the same way PromptTemplates.forModel does it:
# lowercase, separators dropped, first match wins, lookalikes first.
FAMILIES = [
    ("qwen35", None),
    ("qwen3", "Qwen3"),
    ("qwen25", "Qwen2.5"),
    ("smollm2", "SmolLM2"),
    ("smollm3", "SmolLM3"),
    ("llama32", "Llama 3.2"),
    ("phi4mini", "Phi-4-mini"),
    ("gemma3", "Gemma 3"),
    ("lfm25", "LFM 2.5"),
    ("lfm2", "LFM 2.5"),
]

CASES = [
    "trap-arithmetic",
    "multi-step-change",
    "format-constraint",
    "extraction",
    "memory-across-turns",
    "tool-call",
    "tool-result",
]

MARKS = {"pass": "✅", "fail": "❌", "skipped": "—", "error": "💥", None: "·"}


def family_of(name: str) -> str | None:
    normal = re.sub(r"[^a-z0-9]", "", name.lower())
    for key, family in FAMILIES:
        if key in normal:
            return family
    return None


# The file name says which phone produced the report: the matrix runs on several, and a
# report that lost its device would silently overwrite another phone's row. The bare name
# is the Dimensity, which ran first; every later phone got a prefix. The short label is
# what the table columns say, since four devices by two engines do not fit otherwise.
DEVICES = [
    ("qdc-", "8 Gen 3", "8G3"),
    ("tensor-", "Tensor G5", "G5"),
    ("exynos-", "Exynos 2400", "E2400"),
    ("elite-", "8 Elite", "8Elite"),
    ("", "D9400", "D9400"),
]
SHORT = {device: short for _, device, short in DEVICES}
# Columns in the order the phones joined the matrix, which is not the prefix order above:
# the bare prefix has to be matched last and the Dimensity has to be read first.
ORDER = ["D9400", "8 Gen 3", "8 Elite", "Tensor G5", "Exynos 2400"]


def device_of(path: Path) -> str:
    for prefix, device, _ in DEVICES:
        if path.name.startswith(prefix):
            return device
    return DEVICES[-1][1]


def load_reports(results_dir: Path):
    reports = {}
    for path in sorted(results_dir.glob("*.json")):
        report = json.loads(path.read_text())
        engine = "executorch" if "ExecuTorch" in report.get("engine", "") else "llamacpp"
        family = family_of(report["model"])
        if family:
            reports.setdefault(family, {}).setdefault(engine, {})[device_of(path)] = report
    return reports


def case_map(report) -> dict:
    return {case["id"]: case for case in report.get("cases", [])}


def speed(case) -> str:
    prefill = case.get("prompt_tokens", 0)
    prefill_ms = case.get("prefill_ms", 0)
    decode = case.get("generated_tokens", 0)
    decode_ms = case.get("decode_ms", 0)
    parts = []
    if prefill and prefill_ms:
        parts.append(f"{prefill / prefill_ms * 1000:.0f} tok/s in")
    if decode > 1 and decode_ms:
        parts.append(f"{(decode - 1) / decode_ms * 1000:.1f} tok/s out")
    return ", ".join(parts) or "n/a"


def render(reports) -> str:
    lines = [
        "# Backend parity: ExecuTorch vs llama.cpp, same prompts, four SoCs",
        "",
        f"Generated by `tools/eval/run_matrix.sh` on {date.today().isoformat()}. "
        "Greedy decoding on both engines (temperature 0, topK 1), so a rerun after a "
        "backend change reproduces; grades are the device's own, from `ParitySuite`. "
        "Quantisations differ where the publishers' do (a `.pte` is typically 8da4w, "
        "the GGUF counterpart Q4_K_M), so this compares capability, not bit-parity. "
        "D9400 is the Dimensity 9400 (POCO X8 Pro); 8G3 is a Snapdragon 8 Gen 3 on "
        "Qualcomm Device Cloud; G5 is the Tensor G5 (Pixel 10 Pro XL) and E2400 the "
        "Exynos 2400 (Galaxy S24+), 8Elite the Snapdragon 8 Elite (Galaxy S25 Ultra), all "
        "three on Firebase Test Lab via "
        "`tools/eval/run_matrix_ftl.sh`. A grade that differs between two columns of "
        "one engine is a cross-silicon divergence; each is quoted under its table.",
        "",
    ]

    # Only the devices that reported, in the order they joined the matrix, so a rerun on
    # one phone still renders and a column is never empty.
    seen = {device for pair in reports.values() for devices in pair.values() for device in devices}
    devices = [device for device in ORDER if device in seen]
    columns = [(engine, device) for engine in ("executorch", "llamacpp") for device in devices]
    head = (
        "| Case | "
        + " | ".join(f"{'ET' if e == 'executorch' else 'GGUF'} {SHORT[d]}" for e, d in columns)
        + " |"
    )
    rule = "|---|" + "---|" * len(columns)

    for family in sorted(reports):
        pair = reports[family]
        lines.append(f"## {family}")
        lines.append("")
        for engine, label in [("executorch", "ExecuTorch"), ("llamacpp", "llama.cpp")]:
            model = next(iter(pair.get(engine, {}).values()), None)
            if model:
                lines.append(f"- {label} model: `{model['model']}`")
        lines.append("")
        lines.append(head)
        lines.append(rule)
        cases = {
            (engine, device): case_map(report)
            for engine, devices in pair.items()
            for device, report in devices.items()
        }
        for case_id in CASES:
            row = [case_id]
            for key in columns:
                case = cases.get(key, {}).get(case_id)
                row.append(MARKS[case.get("status") if case else None])
            lines.append("| " + " | ".join(row) + " |")
        lines.append("")

        lines.append(head.replace(" |", " speed |").replace("| Case speed |", "| Case |"))
        lines.append(rule)
        for case_id in CASES:
            row = [case_id]
            for key in columns:
                case = cases.get(key, {}).get(case_id)
                row.append(speed(case) if case else "·")
            lines.append("| " + " | ".join(row) + " |")
        lines.append("")

        # Disagreements are the part worth reading, so quote them: between the engines on
        # the same phone, and between the phones on the same engine.
        for case_id in CASES:
            per_column = {
                key: cases.get(key, {}).get(case_id)
                for key in columns
            }
            statuses = {
                key: case.get("status")
                for key, case in per_column.items()
                if case is not None
            }
            if len(set(statuses.values())) > 1:
                lines.append(f"**{case_id}** diverged:")
                lines.append("")
                for (engine, device), status in statuses.items():
                    label = "ExecuTorch" if engine == "executorch" else "llama.cpp"
                    lines.append(
                        f"- {label} on {device} ({status}): "
                        f"{snippet(per_column[(engine, device)])}",
                    )
                lines.append("")
    return "\n".join(lines) + "\n"


def snippet(case) -> str:
    calls = case.get("calls") or []
    if calls:
        call = calls[0]
        return f"call `{call['name']}({call['arguments']})`"
    content = (case.get("content") or case.get("error") or "").strip().replace("\n", " ")
    return f"“{content[:220]}”" if content else "(empty)"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("results_dir", type=Path)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()

    reports = load_reports(args.results_dir)
    if not reports:
        raise SystemExit(f"no reports in {args.results_dir}")
    args.out.write_text(render(reports))
    print(f"wrote {args.out} ({len(reports)} families)")


if __name__ == "__main__":
    main()
